"""Safe HTML rendering helpers for presentation-only SecureScope components."""

from __future__ import annotations

import textwrap

import streamlit as st


def render_html(markup: str) -> None:
    """Render trusted presentation HTML without Markdown interpretation.

    Args:
        markup: Presentation-only HTML generated by SecureScope code. User
            supplied values must be escaped by the caller before interpolation.

    Returns:
        None.

    Raises:
        No exceptions are raised by this helper itself. Streamlit rendering
        errors are propagated to the normal application error boundary.
    """

    normalized = textwrap.dedent(str(markup or "")).strip()
    if not normalized:
        return
    st.html(normalized)
