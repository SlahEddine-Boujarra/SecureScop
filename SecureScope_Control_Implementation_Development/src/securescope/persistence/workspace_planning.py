"""Tenant-scoped planning records with optimistic updates and role checks."""

from __future__ import annotations

import logging
import uuid
from datetime import date, datetime

from psycopg2.extras import Json

from securescope.persistence.foundation_repository import (
    FoundationError,
    member_role,
    workspace_cursor,
)

LOGGER = logging.getLogger(__name__)

KINDS = {
    "risk_group",
    "risk_detail",
    "risk_task",
    "risk_snapshot",
    "risk_comment",
    "risk_review",
    "calendar_event",
    "policy_comment",
    "policy_audit",
}
EDITORS = {"Administrator", "Consultant", "Client contributor"}


def list_records(client: str, kind: str) -> list[dict]:
    """Read scoped supporting records.

    Args:
        client: Exact workspace name.
        kind: Allowlisted record kind.
    Returns:
        Rows in creation order.
    Raises:
        FoundationError: On invalid kind or database failure.
    """
    if kind not in KINDS:
        raise FoundationError("Unknown record type.")
    with workspace_cursor(client) as (cursor, client_id):
        cursor.execute(
            (
                "SELECT * FROM securescope_workspace_records WHERE client_id=%s "
                "AND kind=%s ORDER BY created_at,record_key"
            ),
            (client_id, kind),
        )
        rows = [dict(row) for row in cursor.fetchall()]
        for row in rows:
            row["payload"] = protect_text(row["payload"], decrypt=True)
        return rows


def put_record(
    client: str, kind: str, key: str, payload: dict, *, actor: str, expected: int = 0
) -> str:
    """Save one authorized record without overwriting concurrent changes.

    Args:
        client: Workspace name.
        kind: Record type.
        key: Stable identifier, or blank for a new UUID.
        payload: Validated supporting metadata.
        actor: Trusted session identity.
        expected: Last read revision, zero for creation.
    Returns:
        Saved identifier.
    Raises:
        FoundationError: If unauthorized, invalid or stale.
    """
    if kind not in KINDS or not isinstance(payload, dict):
        raise FoundationError("Invalid supporting record.")
    key = key or str(uuid.uuid4())
    with workspace_cursor(client) as (cursor, client_id):
        role = member_role(cursor, client_id, actor)
        if role not in EDITORS:
            raise FoundationError("An active contributor membership is required.")
        if kind == "risk_review":
            raise FoundationError("Review history is generated by a review transition.")
        validate_payload(cursor, client_id, kind, key, payload, role)
        if (
            kind == "risk_detail"
            and payload.get("review_state") == "Approved"
            and payload.get("approver") != actor
        ):
            raise FoundationError("Only the assigned Administrator may approve this risk.")
        if kind == "risk_group" and role != "Administrator":
            raise FoundationError(
                "Only Administrators may manage risk registers and access grants."
            )
        cursor.execute(
            (
                "SELECT revision FROM securescope_workspace_records WHERE "
                "client_id=%s AND kind=%s AND record_key=%s"
            ),
            (client_id, kind, key),
        )
        old = cursor.fetchone()
        if (old["revision"] if old else 0) != expected:
            raise FoundationError("This record changed. Reload before saving.")
        if kind in {"policy_comment", "policy_audit", "risk_snapshot", "risk_comment"} and old:
            raise FoundationError("History records are append-only.")
        cursor.execute(
            (
                (
                    "INSERT INTO securescope_workspace_records "
                    "(client_id,kind,record_key,payload,updated_by) VALUES "
                    "(%s,%s,%s,%s,%s) ON CONFLICT(client_id,kind,record_key) DO "
                    "UPDATE SET payload=EXCLUDED.payload,revision=securescope_wor"
                    "kspace_records.revision+1,updated_by=EXCLUDED.updated_by,upd"
                    "ated_at=NOW()"
                )
            ),
            (client_id, kind, key, Json(protect_text(payload)), actor),
        )
        if kind == "risk_detail" and payload.get("review_state") in {"In review", "Approved"}:
            event = {
                "risk_ref": payload["risk_ref"],
                "state": payload["review_state"],
                "reviewed_revision": payload["reviewed_revision"],
                "notes": payload.get("notes", ""),
            }
            cursor.execute(
                (
                    "INSERT INTO securescope_workspace_records "
                    "(client_id,kind,record_key,payload,updated_by) VALUES "
                    "(%s,'risk_review',%s,%s,%s)"
                ),
                (client_id, str(uuid.uuid4()), Json(protect_text(event)), actor),
            )
    return key


def delete_group(client: str, key: str, *, actor: str, expected: int, confirmed: bool) -> None:
    """Delete an empty named risk register; never delete canonical risks.

    Args:
        client: Workspace name.
        key: Named group identifier.
        actor: Trusted identity.
        expected: Last observed group revision.
        confirmed: Explicit deletion acknowledgement.
    Returns:
        None.
    Raises:
        FoundationError: If denied, nonempty or stale.
    """
    if not confirmed or key == "default":
        raise FoundationError(
            "Confirm deletion of an empty named register. Default remains available."
        )
    with workspace_cursor(client) as (cursor, client_id):
        if member_role(cursor, client_id, actor) != "Administrator":
            raise FoundationError("Administrator access is required.")
        cursor.execute(
            (
                "SELECT 1 FROM securescope_workspace_records WHERE client_id=%s "
                "AND kind='risk_detail' AND payload->>'group'=%s LIMIT 1"
            ),
            (client_id, key),
        )
        if cursor.fetchone():
            raise FoundationError("Move scenarios to another register before deleting this one.")
        cursor.execute(
            (
                "DELETE FROM securescope_workspace_records WHERE client_id=%s AND "
                "kind='risk_group' AND record_key=%s AND revision=%s"
            ),
            (client_id, key, expected),
        )
        if cursor.rowcount != 1:
            raise FoundationError("Register changed or was already deleted.")


def validate_payload(cursor, client_id: int, kind: str, key: str, payload: dict, role: str) -> None:
    """Validate linked records within the same tenant and enforce review authority."""
    if len(str(payload)) > 500_000:
        raise FoundationError("Record is too large.")
    if kind == "calendar_event":
        if not str(payload.get("title", "")).strip():
            raise FoundationError("Event title is required.")
        try:
            datetime.fromisoformat(payload["starts_at"])
        except (KeyError, TypeError, ValueError) as exc:
            raise FoundationError("A valid event date and time is required.") from exc
    if kind == "calendar_event" and payload.get("linked_type"):
        link_type = payload["linked_type"]
        reference = str(payload.get("linked_reference", "")).strip()
        if link_type == "Risk":
            if not reference.isdigit():
                raise FoundationError("Enter a numeric risk reference.")
            cursor.execute(
                "SELECT risk_ref FROM securescope_risk_register WHERE client_id=%s AND risk_ref=%s",
                (client_id, int(reference)),
            )
            if not cursor.fetchone():
                raise FoundationError("Linked risk does not belong to this workspace.")
            payload.update(route="Risk", risk_ref=int(reference))
        elif link_type == "Asset":
            cursor.execute(
                "SELECT ip FROM securescope_assets WHERE client_id=%s AND ip=%s",
                (client_id, reference),
            )
            if not cursor.fetchone():
                raise FoundationError("Linked asset does not belong to this workspace.")
            payload.update(route="2 · Asset Management", asset_ip=reference)
        elif link_type == "Policy":
            cursor.execute(
                (
                    "SELECT DISTINCT ON (engagement_id,scope_id) "
                    "engagement_id,scope_id,records FROM "
                    "securescope_foundation_versions WHERE client_id=%s AND "
                    "register_key='policy' ORDER BY engagement_id,scope_id,version "
                    "DESC"
                ),
                (client_id,),
            )
            found = None
            for snapshot in cursor.fetchall():
                if any(row.get("policy_id") == reference for row in snapshot["records"]):
                    found = snapshot
                    break
            if not found:
                raise FoundationError(
                    "Linked policy does not belong to this workspace. Use its policy ID."
                )
            payload.update(
                route="Policies",
                policy_id=reference,
                engagement=found["engagement_id"],
                scope=found["scope_id"],
            )
        else:
            raise FoundationError("Unsupported calendar link type.")
    if kind == "risk_group" and not str(payload.get("name", "")).strip():
        raise FoundationError("Register name is required.")
    if kind == "risk_comment":
        cursor.execute(
            "SELECT 1 FROM securescope_risk_register WHERE client_id=%s AND risk_ref=%s",
            (client_id, payload.get("risk_ref")),
        )
        if not cursor.fetchone() or not str(payload.get("body", "")).strip():
            raise FoundationError("Select a saved workspace risk and enter a comment.")
        if payload.get("parent"):
            cursor.execute(
                (
                    "SELECT payload FROM securescope_workspace_records WHERE "
                    "client_id=%s AND kind='risk_comment' AND record_key=%s"
                ),
                (client_id, payload["parent"]),
            )
            parent = cursor.fetchone()
            if not parent or parent["payload"].get("risk_ref") != payload["risk_ref"]:
                raise FoundationError("Reply must belong to the same risk.")
    if kind in {"risk_detail", "risk_task"}:
        ref = payload.get("risk_ref")
        cursor.execute(
            "SELECT * FROM securescope_risk_register WHERE client_id=%s AND risk_ref=%s",
            (client_id, ref),
        )
        risk = cursor.fetchone()
        if not risk:
            raise FoundationError("Select a risk from this workspace.")
        if kind == "risk_detail":
            if str(ref) != key:
                raise FoundationError("Risk metadata identity does not match.")
            if (
                payload.get("expected_risk_revision") is not None
                and payload.pop("expected_risk_revision") != risk["revision"]
            ):
                raise FoundationError(
                    "The assessment changed. Reload before changing its review state."
                )
            state = payload.get("review_state", "Draft")
            if (
                state != "Draft"
                and member_role(cursor, client_id, str(payload.get("approver", "")))
                != "Administrator"
            ):
                raise FoundationError("Select an active Administrator approver.")
            if state not in {"Draft", "In review", "Approved"}:
                raise FoundationError("Invalid review state.")
            if state != "Draft" and (
                not payload.get("approver")
                or not risk.get("risk_owner")
                or not risk.get("pre_likelihood")
                or not risk.get("pre_impact")
            ):
                raise FoundationError(
                    "Set an owner, approver and inherent assessment before review."
                )
            if state == "Approved":
                cursor.execute(
                    (
                        "SELECT payload FROM securescope_workspace_records WHERE "
                        "client_id=%s AND kind='risk_detail' AND record_key=%s"
                    ),
                    (client_id, key),
                )
                prior = cursor.fetchone()
                old = prior["payload"] if prior else {}
                if (
                    role != "Administrator"
                    or old.get("review_state") != "In review"
                    or old.get("reviewed_revision") != risk["revision"]
                ):
                    raise FoundationError(
                        "An Administrator may approve only the current submitted risk revision."
                    )
                # Approval must not silently modify the material submitted metadata.
                for field in ("approver", "category", "group", "review_due"):
                    if payload.get(field) != old.get(field):
                        raise FoundationError("Save changed metadata as a draft before approval.")
            payload["reviewed_revision"] = risk["revision"]
            group = payload.get("group", "default")
            if group != "default":
                cursor.execute(
                    (
                        "SELECT 1 FROM securescope_workspace_records WHERE client_id=%s "
                        "AND kind='risk_group' AND record_key=%s"
                    ),
                    (client_id, group),
                )
                if not cursor.fetchone():
                    raise FoundationError("Selected risk register no longer exists.")
        else:
            if not payload.get("title") or not payload.get("owner"):
                raise FoundationError("Task title and owner are required.")
            if payload.get("status") not in {"Not started", "In progress", "Complete"}:
                raise FoundationError("Invalid task status.")
        if payload.get("review_due"):
            date.fromisoformat(payload["review_due"])
        if payload.get("due"):
            date.fromisoformat(payload["due"])
    if kind in {"policy_comment", "policy_audit"}:
        cursor.execute(
            (
                "SELECT records FROM securescope_foundation_versions WHERE "
                "client_id=%s AND engagement_id=%s AND scope_id=%s AND "
                "register_key='policy' ORDER BY version DESC LIMIT 1"
            ),
            (client_id, payload.get("engagement"), payload.get("scope")),
        )
        snapshot = cursor.fetchone()
        if not snapshot or not any(
            row.get("policy_id") == payload.get("policy_id") for row in snapshot["records"]
        ):
            raise FoundationError("Select a saved policy in this workspace and scope.")
        if kind == "policy_comment":
            if not str(payload.get("body", "")).strip():
                raise FoundationError("Enter a comment.")
            if payload.get("parent"):
                cursor.execute(
                    (
                        "SELECT payload FROM securescope_workspace_records WHERE "
                        "client_id=%s AND kind='policy_comment' AND record_key=%s"
                    ),
                    (client_id, payload["parent"]),
                )
                parent = cursor.fetchone()
                if not parent or any(
                    parent["payload"].get(field) != payload.get(field)
                    for field in ("policy_id", "scope", "engagement")
                ):
                    raise FoundationError("Reply must belong to the same policy.")
        else:
            cursor.execute(
                "SELECT 1 FROM securescope_audit_scopes WHERE client_id=%s AND id=%s",
                (client_id, payload.get("audit_id")),
            )
            if not cursor.fetchone():
                raise FoundationError("Select an audit from this workspace.")


def protect_text(payload: dict, *, decrypt: bool = False) -> dict:
    """Encrypt new narrative fields while keeping indexed link metadata queryable.

    Args:
        payload: Supporting record data.
        decrypt: Whether to resolve encrypted fields for authorized rendering.
    Returns:
        A copy with narrative fields encrypted or decrypted.
    Raises:
        FoundationError: If the host key is missing or cannot decrypt saved text.
    """
    from securescope.integrations.credential_store import (
        CredentialStoreError,
        open_configuration,
        seal_configuration,
    )

    result = dict(payload)
    try:
        if decrypt:
            ciphertext = result.pop("private_text", None)
            if ciphertext:
                result.update(open_configuration(ciphertext.encode()))
        else:
            private = {
                field: result.pop(field)
                for field in (
                    "body",
                    "notes",
                    "description",
                    "risks",
                    "risk_summary",
                    "risk_description",
                    "assessment_conclusion",
                )
                if field in result
            }
            if private and any(private.values()):
                result["private_text"] = seal_configuration(private).decode()
            else:
                result.update(private)
        return result
    except CredentialStoreError as exc:
        LOGGER.warning("Workspace narrative encryption unavailable: %s", type(exc).__name__)
        raise FoundationError(
            (
                "Encrypted notes require the installation's original "
                "SECURESCOPE_CREDENTIAL_ENCRYPTION_KEY. Configure or restore it on"
                " the host."
            )
        ) from exc
